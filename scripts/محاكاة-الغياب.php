/*
 * **ومدّةٌ لا عَلَم**: من تركَ في الخامس عشر يُسأل عن أيامه الأولى.
 * فالورقةُ تُقرأ في نوفمبر عن أكتوبر، والسؤالُ «أكان موظفاً في ذلك
 * اليوم؟» — وإعادةُ الطبع لا تُسقطه مما صُرف عليه أجرُه.
 */
$r = J::rows(base([
    'roster' => [person(1, '1010', 'خالد السعيد') + ['until' => D1]],
]));

check('تركَ في آخر يومٍ محسوم: يُسأل عنه',       kinds($r)['1010|'.D1] ?? null, J::ABSENT);
check('  ولا يُسأل عن اليوم الذي يليه',          isset(kinds($r)['1010|'.D2]), false);

/* ═══════════════════════════════════════════════════════════════════ */
heading('١٦) في إجازة — يُرى ولا يُتَّهم');

$onLeave = ['from_date' => '2026-08-01', 'to_date' => '2026-10-14', 'kind' => 'annual'];

$r = J::rows(base([
    'roster' => [person(1, '1010', 'خالد السعيد') + ['leaves' => [$onLeave]]],
]));

check('في إجازةٍ تُغطّي اليومين: سطران',  count($r), 2);
check('  وأمسُ «في إجازة» لا «لم يبصم»',   kinds($r)['1010|'.D1] ?? null, J::ON_LEAVE);
check('  واليومُ كذلك',                    kinds($r)['1010|'.D2] ?? null, J::ON_LEAVE);
check('  ونصُّ الوسم',                     J::label(J::ON_LEAVE), 'في إجازة');
check('  وهو مصطنَعٌ لا يُعَدّ حضوراً',     J::synthetic(J::ON_LEAVE), true);

/* والمدّةُ تُحمل في الصفّ لتُعرض تحت الوسم فتُراجَع */
check('  والصفُّ يحمل مدّةَ الإجازة',      $r[0]['leave']['kind'] ?? null, 'annual');
check('  ونهايتَها',                       $r[0]['leave']['to'] ?? null, '2026-10-14');

/* وبعد انقضائها يُسأل كغيره */
$ended = ['from_date' => '2026-08-01', 'to_date' => '2026-10-11', 'kind' => 'annual'];

$r = J::rows(base([
    'roster' => [person(1, '1010', 'خالد السعيد') + ['leaves' => [$ended]]],
]));

check('انقضت إجازتُه: يُسأل عن أمس', kinds($r)['1010|'.D1] ?? null, J::ABSENT);

/* ═══════════════════════════════════════════════════════════════════ */
heading('١٧) ترتيبُ الشروط الجديدة — وهو الحكم');

/*
 * **البصمةُ تسبق الإجازة.** فمن بصم وهو مسجَّلٌ في إجازة فقد حضر،
 * والبصمةُ واقعةٌ والإجازةُ ورقة. فيُطبع حضورُه أخضرَ ويبقى التناقضُ
 * ظاهراً لمن يقرأ — فيُراجَع التاريخُ أو يُحتسب له اليوم.
 */
$r = J::rows(base([
    'roster'  => [person(1, '1010', 'خالد السعيد') + ['leaves' => [$onLeave]]],
    'present' => ['1|1010|'.D1 => true],
]));

check('بصم وهو في إجازة: لا سطرَ مصطنَعاً لأمس', isset(kinds($r)['1010|'.D1]), false);

/* وبصمةٌ في موقعٍ آخرَ تسبقها كذلك */
$r = J::rows(base([
    'roster'   => [person(1, '1010', 'خالد السعيد') + ['leaves' => [$onLeave]]],
    'anywhere' => [D1 => ['n|خالد السعيد' => [2]]],
]));

check('بصم في موقعٍ آخرَ وهو في إجازة: «في موقعٍ آخر»',
    kinds($r)['1010|'.D1] ?? null, J::ELSEWHERE);

/*
 * **وتركُ العمل يسبق الإجازة.** فمن تركَ ثم بقيت له إجازةٌ مسجَّلةٌ
 * قديمة لا يُكتب له سطرُ إجازةٍ بعد تركه — وإلا ظهر في الكشف من ليس
 * من الشركة.
 */
$r = J::rows(base([
    'roster' => [person(1, '1010', 'خالد السعيد') + [
        'until'  => '2026-10-11',
        'leaves' => [$onLeave],
    ]],
]));

check('تركَ العملَ وله إجازةٌ سارية: لا سطر', count($r), 0);

/*
 * **والإجازةُ تسبق «لم يُحسم» و«لا بيانات».** فهي واقعةٌ مكتوبةٌ، وهما
 * جهلٌ بالحال. والمكتوبُ أولى من المجهول.
 */
$r = J::rows(base([
    'roster'          => [person(1, '1010', 'خالد السعيد') + ['leaves' => [$onLeave]]],
    'settled_through' => '2026-10-01',
    'coverage'        => [1 .'|'.D1 => false, 1 .'|'.D2 => false],
]));

check('إجازةٌ في يومٍ لم يُحسم وتغطيتُه ناقصة: «في إجازة»',
    kinds($r)['1010|'.D1] ?? null, J::ON_LEAVE);

/* والمستقبلُ يسبق الجميع */
$r = J::rows(base([
    'roster'   => [person(1, '1010', 'خالد السعيد') + ['leaves' => [$onLeave]]],
    'calendar' => cal(['2026-10-25']),
    'coverage' => fullCoverage([1], ['2026-10-25']),
]));

check('يومٌ لم يجئ وفيه إجازة: لا سطر', count($r), 0);
/* ═══════════════════════════════════════════════════════════════════ */
heading('١٨) النقلُ بين المشاريع');

/* نُقل منه قبل المدّة: لا يُسأل عنه هنا بتّة */
$r = J::rows(base([
    'roster' => [array_merge(person(1, '1010', 'خالد السعيد'), [
        'serves' => [['from' => '2026-01-01', 'to' => '2026-10-11']],
    ])],
]));

check('نُقل منه قبل المدّة: لا سطر', count($r), 0);

/* نُقل منه في وسط المدّة: يُسأل عن أيامه الأولى وحدَها */
$r = J::rows(base([
    'roster' => [array_merge(person(1, '1010', 'خالد السعيد'), [
        'serves' => [['from' => '2026-01-01', 'to' => D1]],
    ])],
]));

check('نُقل في وسط المدّة: يُسأل عن آخر يومٍ له', kinds($r)['1010|'.D1] ?? null, J::ABSENT);
check('  ولا يُسأل عمّا بعده',                   isset(kinds($r)['1010|'.D2]), false);

/*
 * **النقضُ الأوّل:** الانتظارُ يُقصّ بأوّلِ بصمةٍ بعد الوصول لا بآخرِها.
 *
 * فلو قيس بآخر بصمةٍ لانقلب الحكمُ بأثرٍ رجعيّ: تُطبع الورقةُ فتقول
 * «نُقل ولم يبصم» رماديّاً، ثم تُعاد طباعتُها بعد أن يُسجَّل إصبعُه
 * فتقول «لم يبصم» **أحمرَ** عن الأيام نفسِها. وورقةٌ تُغيّر حكمَها عند
 * إعادة طبعها لا يُوثق بها في شيء.
 */
$r = J::rows(base([
    'roster' => [array_merge(person(2, '77', 'خالد السعيد'), [
        'serves'    => [['from' => D1, 'to' => null]],
        'awaiting'  => D1,
        'seen_from' => null,      // لم تصل منه بصمةٌ بعد
    ])],
    'coverage' => fullCoverage([1, 2], [D1, D2]),
]));

$k = kinds($r);

check('(نقضٌ) نُقل ولم يُسجَّل إصبعُه: رماديٌّ لا أحمر', $k['77|'.D1] ?? null, J::AWAITING);
check('  ونصُّه',                                        J::label(J::AWAITING), 'نُقل ولم يبصم بعد');
check('  وشارتُه ليست حمراء',                            J::badge(J::AWAITING), 'bg-secondary-subtle text-secondary-emphasis');
check('  وهو مصطنَعٌ لا حضور',                           J::synthetic(J::AWAITING), true);

/* ولمّا سُجّل إصبعُه في اليوم الثاني: الأوّلُ يبقى رماديّاً والثاني يُسأل */
$r = J::rows(base([
    'roster' => [array_merge(person(2, '77', 'خالد السعيد'), [
        'serves'    => [['from' => D1, 'to' => null]],
        'awaiting'  => D1,
        'seen_from' => D2,        // أوّلُ بصمةٍ وصلت في اليوم الثاني
    ])],
    'coverage' => fullCoverage([1, 2], [D1, D2]),
]));

$k = kinds($r);

check('  وبعد تسجيل إصبعه: أمسُ يبقى رماديّاً', $k['77|'.D1] ?? null, J::AWAITING);
check('  ولا ينقلب أحمرَ بأثرٍ رجعيّ',          ($k['77|'.D1] ?? null) === J::ABSENT, false);

/*
 * **والانتظارُ آخرُ السلسلة**: لا يبتلع حكماً قائماً.
 */
$r = J::rows(base([
    'roster' => [array_merge(person(2, '77', 'خالد السعيد'), [
        'serves'    => [['from' => D1, 'to' => null]],
        'awaiting'  => D1,
        'seen_from' => null,
        'leaves'    => [['from_date' => D1, 'to_date' => D2, 'kind' => 'annual']],
    ])],
    'coverage' => fullCoverage([1, 2], [D1, D2]),
]));

check('الإجازةُ تسبق الانتظار', kinds($r)['77|'.D1] ?? null, J::ON_LEAVE);

$r = J::rows(base([
    'roster' => [array_merge(person(2, '77', 'خالد السعيد'), [
        'serves'    => [['from' => D1, 'to' => null]],
        'awaiting'  => D1,
        'seen_from' => null,
    ])],
    'present'  => ['2|77|'.D1 => true],
    'coverage' => fullCoverage([1, 2], [D1, D2]),
]));

check('والبصمةُ تسبقه — لا سطرَ لأمس', isset(kinds($r)['77|'.D1]), false);

$r = J::rows(base([
    'roster' => [array_merge(person(2, '77', 'خالد السعيد'), [
        'serves'    => [['from' => D1, 'to' => null]],
        'awaiting'  => D1,
        'seen_from' => null,
    ])],
    'coverage' => [2 .'|'.D1 => false, 2 .'|'.D2 => true],
]));

check('و«لا بيانات» تسبقه', kinds($r)['77|'.D1] ?? null, J::NODATA);

/*
 * **النقضُ الثاني:** الوسيطُ السادس لا يُمرَّر بالموضع.
 *
 * فلو مُرّر لأصاب خانةَ الإجازة، فاختفت مدّةُ الإجازة من كل سطرٍ رماديٍّ
 * في الكشف — وهي التي تُراجَع بها التواريخ.
 */
$r = J::rows(base([
    'roster' => [person(1, '1010', 'خالد السعيد') + [
        'leaves' => [['from_date' => D1, 'to_date' => D2, 'kind' => 'sick']],
    ]],
]));

check('سطرُ الإجازة ما زال يحمل مدّتَها', $r[0]['leave']['kind'] ?? null, 'sick');
check('  وخانةُ النقل موجودةٌ فارغة',       array_key_exists('moved', $r[0]) && $r[0]['moved'] === null, true);

$r = J::rows(base([
    'roster' => [array_merge(person(2, '77', 'خالد السعيد'), [
        'serves' => [['from' => D1, 'to' => null]], 'awaiting' => D1, 'seen_from' => null,
    ])],
    'coverage' => fullCoverage([1, 2], [D1, D2]),
]));

check('وسطرُ الانتظار يحمل تاريخَ وصوله', $r[0]['moved']['since'] ?? null, D1);
check('  وخانةُ الإجازة موجودةٌ فارغة',     array_key_exists('leave', $r[0]) && $r[0]['leave'] === null, true);

/* ونقلٌ عائد: أ ← ب ← أ، فيُسأل عن مدّتيه في (أ) ولا يُسأل بينهما */
$r = J::rows(base([
    'roster'   => [array_merge(person(1, '1010', 'خالد السعيد'), [
        'serves' => [['from' => '2026-01-01', 'to' => '2026-05-31'], ['from' => D1, 'to' => null]],
    ])],
    'calendar' => cal(['2026-03-02', '2026-07-01', D1]),
    'coverage' => fullCoverage([1], ['2026-03-02', '2026-07-01', D1]),
]));

$k = kinds($r);

check('نقلٌ عائد: يُسأل عن مدّته الأولى', $k['1010|2026-03-02'] ?? null, J::ABSENT);
check('  ولا يُسأل عمّا بينهما',          isset($k['1010|2026-07-01']), false);
check('  ويُسأل عن مدّته الثانية',        $k['1010|'.D1] ?? null, J::ABSENT);
/* ═══════════════════════════════════════════════════════════════════ */
heading('١٤) قصّةُ موقعٍ كامل');

/*
 * تربية الأحمدي: سبعةٌ مربوطون. بصم خمسةٌ أمسِ، وأُعير سادسٌ إلى الجهراء،
 * وغاب السابع. فالمطلوبُ سطرٌ أحمرُ واحدٌ لا سبعة.
 */
$roster = [
    person(1, '1002', 'خالد راكان المحمد'),
    person(1, '1005', 'سرينيفاسولو ساجيثا'),
    person(1, '1006', 'عبدالله عبدالسلام'),
    person(1, '1003', 'مؤمن عبد العال'),
    person(1, '1008', 'محمد العطافي'),
    person(1, '1007', 'محمد خضر الحسنات'),
    person(1, '1010', 'خالد السعيد'),
];

$present = [];

foreach (['1002', '1005', '1006', '1003', '1008'] as $p) {
    $present['1|'.$p.'|'.D1] = true;
}

$r = J::rows(base([
    'roster'          => $roster,
    'present'         => $present,
    'anywhere'        => [D1 => ['n|محمد خضر الحسنات' => [2]]],
    'calendar'        => cal([D1]),
    'coverage'        => fullCoverage([1, 2], [D1]),
    'settled_through' => D1,
]));

$k = kinds($r);

check('سطران لا سبعة',                   count($r), 2);
check('  الغائبُ وحدَه أحمر',             $k['1010|'.D1] ?? null, J::ABSENT);
check('  والمُعارُ «في موقعٍ آخر»',       $k['1007|'.D1] ?? null, J::ELSEWHERE);
check('  ومن بصم لا سطرَ له',             isset($k['1002|'.D1]), false);

$red = array_filter($r, fn ($x) => $x['kind'] === J::ABSENT);
check('وعددُ المتَّهمين واحدٌ من سبعة', count($red), 1);

/* ═══════════════════════════════════════════════════════════════════ */
echo "\n".str_repeat('═', 64)."\n";
echo $fail === 0
    ? "  ✓ نجحت {$pass} حالةً كلُّها.\n"
    : "  ✗ نجحت {$pass} وفشلت {$fail}.\n";
echo str_repeat('═', 64)."\n";

exit($fail === 0 ? 0 : 1);
