$pass = $fail = 0;

function check(string $what, mixed $got, mixed $want): void
{
    global $pass, $fail;

    if ($got === $want) {
        $pass++;
        echo "  ✓ {$what}\n";

        return;
    }

    $fail++;
    echo "  ✗ {$what}\n      جاء: ".var_export($got, true)
        ."\n      والمتوقَّع: ".var_export($want, true)."\n";
}

function heading(string $t): void
{
    echo "\n".str_repeat('─', 64)."\n  {$t}\n".str_repeat('─', 64)."\n";
}

