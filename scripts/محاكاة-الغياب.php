/** تقويمٌ من تواريخَ متتاليةٍ أيامُها دوام، إلا ما سُمّي */
function cal(array $dates, array $off = []): array
{
    $out = [];

    foreach ($dates as $d) {
        $out[$d] = $off[$d] ?? 'working';
    }

    return $out;
}

/** تغطيةٌ تامّةٌ لكل موقعٍ في كل يوم */
function fullCoverage(array $sites, array $dates): array
{
    $c = [];

    foreach ($sites as $s) {
        foreach ($dates as $d) {
            $c[$s.'|'.$d] = true;
        }
    }

    return $c;
}

function person(int $site, string $pin, string $name, ?string $ref = null, string $since = '0000-01-01'): array
{
    return [
        'site_id' => $site, 'device_pin' => $pin, 'employee' => $name,
        'employee_ref' => $ref, 'job_title' => 'عامل', 'since' => $since,

        /* مُدَدُ الخدمة — مفتوحةٌ من $since ما لم تُعدَّل في الحالة */
        'serves' => [['from' => $since, 'to' => null]],
    ];
}

/** الحالاتُ المُخرَجة مفتاحُها «رقم|تاريخ» — لقراءةٍ مختصرة */
function kinds(array $rows): array
{
    $out = [];

    foreach ($rows as $r) {
        $out[$r['device_pin'].'|'.$r['work_date']] = $r['kind'];
    }

    return $out;
}

