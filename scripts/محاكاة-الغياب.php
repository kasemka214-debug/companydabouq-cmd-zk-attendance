 *
 * وعطبُه صامت: لا استثناءَ ولا سطرَ خطأ — إنما كلُّ من بصم يخرج غائباً.
 * فيُثبَّت هنا أن المطابقةَ لفظيةٌ صارمة، ليُعلم أن القصَّ في `AbsenceFinder`
