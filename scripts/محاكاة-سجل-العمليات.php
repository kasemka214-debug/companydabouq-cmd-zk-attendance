/*
 * بديلُ `Clock::fromDevice` — يُفسّر طابعَ الجهاز بمنطقته ثم يحوّله UTC.
 * وبغيره لا تُقاس المحاكاةُ على شيء: الجهازُ يرسل ساعتَه عاريةً بلا منطقة.
 */
namespace App\Support {
    class Clock
    {
        public static function fromDevice(?string $stamp): ?\DateTimeImmutable
        {
            $stamp = trim((string) $stamp);

            if ($stamp === '') {
                return null;
            }

            try {
                $d = new \DateTimeImmutable($stamp, new \DateTimeZone('Asia/Kuwait'));

                return $d->setTimezone(new \DateTimeZone('UTC'));
            } catch (\Throwable) {
                return null;
            }
        }
    }
}

namespace {

require __DIR__.'/../app/Services/OperationParser.php';

use App\Services\OperationParser as P;

$pass = $fail = 0;

function check(string $what, mixed $got, mixed $want): void
{
    global $pass, $fail;

    if ($got === $want) {
        $pass++;
        echo "  ✓ {$what}\n";

        return;
    }

    $fail++;
    echo "  ✗ {$what}\n      جاء: ".var_export($got, true)
        ."\n      والمتوقَّع: ".var_export($want, true)."\n";
}

function heading(string $t): void
{
    echo "\n".str_repeat('─', 62)."\n  {$t}\n".str_repeat('─', 62)."\n";
}

$p = new P;

/* ═══════════════════════════════════════════════════════════════════ */
heading('١) الصيغةُ بالجدولة — وهي الأشيع');

$rows = $p->parse("OPLOG\t21\t8\t2026-09-28 08:14:03\t0\t0\t0\t0");

check('سطرٌ واحدٌ قُرئ',       count($rows), 1);
check('والرمزُ ٢١',            $rows[0]['op_code'], 21);
check('والمسؤولُ رقمُ ٨',      $rows[0]['operator_pin'], '8');
check('والوقتُ حُوّل إلى UTC', $rows[0]['occurred_at']?->format('Y-m-d H:i:s'), '2026-09-28 05:14:03');
check('وهو يمسّ الوقت',        P::touchesTime(21), true);
check('واسمُه بالعربية',        P::label(21), 'تغييرُ الساعة');

/* ═══════════════════════════════════════════════════════════════════ */
heading('٢) الصيغةُ بالمسافات — بعضُ الإصدارات لا تُجدول');

/*
 * والمسافةُ الواحدةُ تكسر الوقتَ حقلين («2026-09-28» و«08:14:03»)، فيُجمع
 * ما بعد الرقم حتى يُقرأ طابعاً. ولولا هذا لخرج الوقتُ فارغاً — وتقريرٌ
 * بوقتٍ فارغٍ لا يُقرأ في مواجهة.
 */
$rows = $p->parse('OPLOG 21 8 2026-09-28 08:14:03 0 0 0 0');

check('قُرئ السطر',            count($rows), 1);
check('والرمزُ ٢١',            $rows[0]['op_code'] ?? null, 21);
check('والمسؤولُ ٨',           $rows[0]['operator_pin'] ?? null, '8');
check('والوقتُ جُمع من حقلين', $rows[0]['occurred_at']?->format('H:i:s'), '05:14:03');

/* ═══════════════════════════════════════════════════════════════════ */
heading('٣) ما يُطرح');

$mixed = implode("\n", [
    'OPLOG	21	8	2026-09-28 08:14:03	0	0	0	0',
    'OPLOG	29	1	2026-09-28 08:15:00	0	0	0	0',   /* فتحُ باب — مقبول */
    'OPLOG	99	1	2026-09-28 08:16:00	0	0	0	0',   /* رمزٌ لا نعرفه */
    'USER PIN=1001	Name=أحمد	Pri=0',                        /* مستخدم، لا عملية */
    'FP PIN=1001	FID=1	TMP='.str_repeat('A', 300),        /* قالبُ بصمة */
    '',
    'OPLOG	x	1	2026-09-28	0',                            /* رمزٌ ليس رقماً */
]);

$rows = $p->parse($mixed);

check('قُرئ المعروفُ وحدَه (٢١ و٢٩)', count($rows), 2);
check('والأوّلُ ٢١',                    $rows[0]['op_code'], 21);
check('والثاني ٢٩',                     $rows[1]['op_code'], 29);
check('و٢٩ لا يمسّ الوقت',              P::touchesTime(29), false);
check('ورمزٌ مجهولٌ له وصفٌ لا يُفشل',   P::label(77), 'عمليةٌ رقم 77');

/* ═══════════════════════════════════════════════════════════════════ */
heading('٤) الأحوالُ الشاذّة — ولا تُسقط الدفعة');

/*
 * والتساهلُ هنا ضرورة: الجهازُ يُعيد الدفعةَ كلَّها إن لم نُقِرّ باستلامها،
 * فلو أسقطنا مئةَ سطرٍ من أجل واحدٍ فاسدٍ دار الجهازُ على الدفعة نفسها
 * إلى الأبد ولَما وصل شيء — لا عمليةٌ ولا اسمُ موظف.
 */
check('نصٌّ فارغ',                     count($p->parse('')), 0);
check('سطرٌ ليس OPLOG',                count($p->parse('ATTLOG 1 2 3')), 0);
check('OPLOG بلا شيءٍ بعده',           count($p->parse('OPLOG')), 0);
check('OPLOG برمزٍ وحدَه',              count($p->parse("OPLOG\t21")), 1);

$bare = $p->parse("OPLOG\t21");
check('  والمسؤولُ فيه فارغٌ لا صفر',   $bare[0]['operator_pin'], null);
check('  والوقتُ null لا يُختلَق',      $bare[0]['occurred_at'], null);

$zero = $p->parse("OPLOG\t21\t0\t2026-09-28 08:14:03");
check('ومسؤولٌ «٠» يُقرأ فارغاً',        $zero[0]['operator_pin'], null);

$bad = $p->parse("OPLOG\t21\t8\tوقتٌ فاسد\t0");
check('ووقتٌ فاسدٌ يصير null والسطرُ يبقى', $bad[0]['occurred_at'], null);
check('  والرمزُ والمسؤولُ سلِما',          $bad[0]['operator_pin'], '8');

/* ═══════════════════════════════════════════════════════════════════ */
heading('٥) قصّةٌ كاملة — من غيّر الساعةَ ثم أعادها');

/*
 * عاملٌ جاء الثامنةَ ويريد السابعة: يفتح القائمة (٤)، يُرجع الساعة (٢١)،
 * يبصم، ثم يُعيدها (٢١). فيصل السجلُّ بأربعة أسطرَ فيها رقمُه مرّتين.
 *
 * والمقصودُ من الفحص أن الرقمَ لا يضيع: تقريرٌ يقول «عُبث بساعة الجهاز»
 * ولا يقول بيدِ من لا ينفع في نزاعٍ على أجر.
 */
$story = implode("\n", [
    'OPLOG	4	12	2026-09-28 08:02:10	0	0	0	0',
    'OPLOG	21	12	2026-09-28 07:02:40	0	0	0	0',   /* أرجعها ساعة */
    'OPLOG	21	12	2026-09-28 08:11:05	0	0	0	0',   /* ثم أعادها */
    'OPLOG	5	12	2026-09-28 08:11:30	0	0	0	0',
]);

$rows = $p->parse($story);

check('قُرئت الأربعةُ كلُّها', count($rows), 4);

$timeOps = array_values(array_filter($rows, fn ($r) => P::touchesTime($r['op_code'])));
check('ومنها اثنتان تمسّان الوقت', count($timeOps), 2);

$who = array_unique(array_column($rows, 'operator_pin'));
check('والفاعلُ واحدٌ رقمُه ١٢', array_values($who), ['12']);

/*
 * ولاحِظ: الوقتُ الذي ادّعاه الجهازُ في السطر الثاني (٧:٠٢) **بالساعة
 * المغيَّرة نفسِها** — فهو مكتوبٌ بالكذب الذي نحقّق فيه. ولهذا يُخزَّن
 * وقتُ الوصول بجنبه، وعليه وحدَه يُبنى نطاقُ الضرر.
 */
check('والسطرُ الثاني يحمل الوقتَ المغيَّر كما ادّعاه',
    $timeOps[0]['occurred_at']?->format('H:i'), '04:02');

/* ═══════════════════════════════════════════════════════════════════ */
echo "\n".str_repeat('═', 62)."\n";
echo $fail === 0
    ? "  ✓ نجحت {$pass} حالةً كلُّها.\n"
    : "  ✗ نجحت {$pass} وفشلت {$fail}.\n";
echo str_repeat('═', 62)."\n";

exit($fail === 0 ? 0 : 1);

}
