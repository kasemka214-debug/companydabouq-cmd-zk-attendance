$pass = $fail = 0;

function check(string $what, mixed $got, mixed $want): void
{
    global $pass, $fail;

    /* المقارنةُ متساهلةٌ في النوع: 31 و31.0 شيءٌ واحدٌ في هذا المقام */
    $ok = is_numeric($got) && is_numeric($want)
        ? abs((float) $got - (float) $want) < 0.0001
        : $got === $want;

    if ($ok) {
        $pass++;
        echo "  ✓ {$what}\n";

        return;
    }

    $fail++;
    $g = var_export($got, true);
    $w = var_export($want, true);
    echo "  ✗ {$what}\n      جاء: {$g}\n      والمتوقَّع: {$w}\n";
}

function heading(string $t): void
{
    echo "\n".str_repeat('─', 62)."\n  {$t}\n".str_repeat('─', 62)."\n";
}

/* حالةُ دفعةٍ حيّةٍ سليمة — تُعدَّل منها كلُّ حالةٍ أخرى */
function batch(array $over = []): array
{
    return $over + ['stored' => 1, 'rows' => 1, 'span' => 0, 'gap_before' => 30, 'after_sync' => false];
}

