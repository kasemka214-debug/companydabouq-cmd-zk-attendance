<?php

/**
 * محاكاةُ حارس ساعة الجهاز.
 *
 * والبصمةُ تُختم بساعة الجهاز لا بساعة الخادم. فمن فتح قائمة الجهاز
 * وأخّر ساعتَه ساعتين ثم بصم، سُجّل حضورُه قبل ساعتين — ولا يبدو في
 * السطر نفسِه شيءٌ غريب.
 *
 * وهذا يفحص شيئين: قياسَ الفرق ووصفَه، وترميزَ الوقت الذي يفهمه الجهاز
 * حين نأمره أن يضبط ساعته. والترميزُ موضعُ خطأٍ خفيّ: ZKTeco تعدّ الشهرَ
 * واحداً وثلاثين يوماً دائماً، فحسابُه بالتقويم الميلادي يضبط الساعةَ
 * على يومٍ غير يومها.
 *
 *     C:\xampp\php\php.exe scripts/محاكاة-الساعة.php
 */

declare(strict_types=1);

const TOLERANCE = 300;   /* خمسُ دقائق */

function clockLabel(?int $drift): string
{
    if ($drift === null) {
        return 'لم يُقَس بعد';
    }

    $abs = abs($drift);

    if ($abs <= TOLERANCE) {
        return 'مضبوطة';
    }

    $unit = $abs >= 3600
        ? number_format($abs / 3600, 1).' ساعة'
        : intdiv($abs, 60).' دقيقة';

    return $drift > 0 ? "مقدَّمة {$unit}" : "مؤخَّرة {$unit}";
}

function suspect(?int $drift): bool
{
    return $drift !== null && abs($drift) > TOLERANCE;
}

/** ترميزُ ZKTeco: الشهرُ واحدٌ وثلاثون يوماً دائماً */
function encodeTime(int $y, int $m, int $d, int $h, int $i, int $s): int
{
    return ((($y - 2000) * 12 * 31) + (($m - 1) * 31) + ($d - 1)) * 86400
        + ($h * 3600) + ($i * 60) + $s;
}

/* ─── الفحص ─── */

$pass = 0;
$fail = 0;

function check(string $what, $got, $want): void
{
    global $pass, $fail;

    $ok = $got === $want;
    $ok ? $pass++ : $fail++;

    printf("%s %-50s %s%s\n", $ok ? '  ✓' : '  ✗', $what,
        is_scalar($got) || $got === null ? var_export($got, true) : gettype($got),
        $ok ? '' : '   ← المتوقَّع: '.var_export($want, true));
}

echo "\n─── ١) الساعةُ المضبوطة لا تُنبَّه ───\n";

check('فرقٌ صفر',            suspect(0), false);
check('ثانيتان',             suspect(2), false);
check('أربعُ دقائق',         suspect(240), false);
check('خمسُ دقائقَ تماماً',  suspect(300), false);
check('ووصفُها',             clockLabel(12), 'مضبوطة');

echo "\n─── ٢) الساعةُ المؤخَّرة — وهي حيلةُ من يريد حضوراً مبكّراً ───\n";

check('ساعتان إلى الوراء تُنبَّه', suspect(-7200), true);
check('ووصفُها',                   clockLabel(-7200), 'مؤخَّرة 2.0 ساعة');
check('نصفُ ساعة',                 clockLabel(-1800), 'مؤخَّرة 30 دقيقة');
check('عشرُ دقائق',                clockLabel(-600), 'مؤخَّرة 10 دقيقة');

echo "\n─── ٣) البصمةُ من المستقبل — دليلٌ قاطع ───\n";

/*
 * لا انقطاعَ يُنتج بصمةً لم تقع بعد. فالتأخّرُ يحتمل وجهين — انقطاعٌ
 * يُدرِك ما فاته، أو ساعةٌ أُخِّرت — أمّا التقدّمُ فلا يحتمل إلا واحداً.
 */
check('ساعةٌ إلى الأمام',  suspect(3600), true);
check('ووصفُها',           clockLabel(3600), 'مقدَّمة 1.0 ساعة');
check('ربعُ ساعة',         clockLabel(900), 'مقدَّمة 15 دقيقة');

echo "\n─── ٤) ما لم يُقَس ───\n";

check('بلا قياس',   suspect(null), false);
check('ووصفُه',     clockLabel(null), 'لم يُقَس بعد');

echo "\n─── ٥) ترميزُ الوقت — الشهرُ ٣١ يوماً دائماً ───\n";

/* أوّلُ لحظةٍ في التقويم: 2000-01-01 00:00:00 = صفر */
check('مبدأُ التقويم', encodeTime(2000, 1, 1, 0, 0, 0), 0);

/* ثانيةٌ واحدة */
check('ثانيةٌ بعده', encodeTime(2000, 1, 1, 0, 0, 1), 1);

/* يومٌ كامل */
check('يومٌ بعده', encodeTime(2000, 1, 2, 0, 0, 0), 86400);

/* شهرٌ كامل — واحدٌ وثلاثون يوماً لا ثمانيةٌ وعشرون */
check('شهرٌ بعده = ٣١ يوماً', encodeTime(2000, 2, 1, 0, 0, 0), 31 * 86400);

/* سنةٌ كاملة — اثنا عشرَ شهراً × ٣١ */
check('سنةٌ بعده = ٣٧٢ يوماً', encodeTime(2001, 1, 1, 0, 0, 0), 12 * 31 * 86400);

/*
 * ولو حُسب بالتقويم الميلادي لكان الفرقُ بين أوّل فبراير وأوّل يناير
 * واحداً وثلاثين يوماً في يناير، لكنّ الفرقَ بين أوّل مارس وأوّل فبراير
 * ثمانيةً وعشرين — وترميزُ ZKTeco يجعله واحداً وثلاثين في الحالين.
 */
$feb = encodeTime(2026, 2, 1, 0, 0, 0);
$mar = encodeTime(2026, 3, 1, 0, 0, 0);

check('فبراير→مارس = ٣١ يوماً في الترميز', intdiv($mar - $feb, 86400), 31);

/* لحظةٌ واقعية: 2026-09-27 14:35:20 */
$enc = encodeTime(2026, 9, 27, 14, 35, 20);
$expected = (((26 * 12 * 31) + (8 * 31) + 26) * 86400) + (14 * 3600) + (35 * 60) + 20;

check('لحظةٌ واقعية', $enc, $expected);
check('وهي موجبة',    $enc > 0, true);

echo "\n".str_repeat('─', 68)."\n";
printf("  نجح %d، وفشل %d.\n\n", $pass, $fail);

exit($fail === 0 ? 0 : 1);
